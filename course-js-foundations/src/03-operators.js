// Operadores aritméticos
// Suma (+)

const sum = 5 + 3; // 8
console.log("Suma:", sum);

// Resta (-)
const difference = 10 - 4; // 6
console.log("Resta:", difference);

// Multiplicación (*)
const product = 6 * 7; // 42
console.log("Multiplicación:", product);

// División (/)
const quotient = 20 / 5; // 4
console.log("División:", quotient);

// Módulo (%)
const remainder = 10 % 3; // 1
console.log("Módulo:", remainder);

// Exponenciación (**)
const power = 2 ** 3; // 8
console.log("Exponenciación:", power);

// Operadores de asignación

//Asignación con suma.

